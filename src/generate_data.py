"""Deterministic serverless source generator; immutable, resumable file publication.

Run from the project venv: python src/generate_data.py --profile Faisal
For Step 4: add --day 2026-11-01. No overwrite or deletion of published data.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
from datetime import date
import io
import json
from pathlib import Path
import uuid

from databricks.connect import DatabricksSession
from databricks.sdk import WorkspaceClient
from databricks.sdk.errors import NotFound
from pyspark.sql import functions as F

VERSION = "v1"
START = date(2026, 9, 1)
ROOT = "/Volumes/rafa/dev_tariq_faisal1999_payments_raw/raw_data"


def uniform(key, salt):
    return F.pmod(F.xxhash64(F.col(key), F.lit(salt)), F.lit(1000000)) / F.lit(1000000.0)


def identifier(prefix, col):
    return F.concat(F.lit(prefix), F.lpad(col.cast("string"), 10, "0"))


def read_json(w, path):
    try:
        return json.loads(w.files.download(path).contents.read())
    except NotFound:
        return None


def write_json(w, path, value, overwrite=True):
    w.files.create_directory(path.rsplit("/", 1)[0])
    w.files.upload(path, io.BytesIO(json.dumps(value, indent=2).encode()), overwrite=overwrite)


def files_below(w, path):
    # Metadata-only recursion, never driver-side data generation.
    for entry in w.files.list_directory_contents(path):
        if entry.is_directory:
            yield from files_below(w, entry.path)
        elif entry.path.endswith(".parquet"):
            yield entry.path


def publish(w, source, source_root, target_root):
    objects = sorted(files_below(w, source_root))

    def copy_one(path):
        destination = target_root + path[len(source_root):]
        try:
            metadata = w.files.get_metadata(destination)
            original = w.files.get_metadata(path)
            if metadata.content_length != original.content_length:
                raise RuntimeError(f"Immutable file size mismatch: {destination}")
            return
        except NotFound:
            pass
        w.files.create_directory(destination.rsplit("/", 1)[0])
        with w.files.download(path).contents as stream:
            w.files.upload(destination, stream, overwrite=False)

    with ThreadPoolExecutor(max_workers=8) as pool:
        list(pool.map(copy_one, objects))
    print(f"Published {source}: {len(objects)} files", flush=True)
    return len(objects)


def base_customers(spark):
    # Tiny Faker vocabulary only; all 10K source records are generated by Spark.
    # Avoid remote Python UDFs: this workspace's isolated UDF container cannot start.
    from faker import Faker
    fake = Faker("en_US")
    fake.seed_instance(901)
    first_names = F.array(*[F.lit(fake.first_name()) for _ in range(128)])
    last_names = F.array(*[F.lit(fake.last_name()) for _ in range(128)])
    name = F.concat_ws(" ", F.element_at(first_names, (F.floor(uniform("customer_idx", 70) * 128) + 1).cast("int")),
        F.element_at(last_names, (F.floor(uniform("customer_idx", 71) * 128) + 1).cast("int")))

    return (spark.range(10000).withColumnRenamed("id", "customer_idx")
        .withColumn("customer_id", identifier("C", F.col("customer_idx")))
        .withColumn("name", name)
        .withColumn("tier", F.when(F.col("customer_idx") < 500, "enterprise")
                    .when(F.col("customer_idx") < 3500, "pro").otherwise("standard"))
        .withColumn("region", F.when(uniform("customer_idx", 1) < .45, "North America")
                    .when(uniform("customer_idx", 1) < .73, "Europe")
                    .when(uniform("customer_idx", 1) < .92, "Asia Pacific").otherwise("Latin America")))


def products(spark):
    return (spark.range(200).withColumnRenamed("id", "product_idx")
        .withColumn("product_id", identifier("P", F.col("product_idx")))
        .withColumn("category", F.when(F.col("product_idx") < 150, "consumer").otherwise("business"))
        .withColumn("unit_price", F.round(F.when(F.col("product_idx") < 150,
            15 + 50 * uniform("product_idx", 2)).otherwise(60 + 200 * uniform("product_idx", 2)), 2))
        .withColumn("ingestion_date", F.lit("2026-09-01").cast("date")))


def build_orders(spark, customers, catalog, day):
    # Hour candidates plus weighted acceptance yield diurnal and weekly seasonality.
    # Each candidate is independently seeded so incremental days match full generation.
    first_day = (date.fromisoformat(day) - START).days if day else 0
    last_day = first_day + 1 if day else 61
    candidates = (spark.range(first_day * 4000, last_day * 4000)
        .withColumnRenamed("id", "order_idx")
        .withColumn("day_idx", F.floor(F.col("order_idx") / 4000).cast("int"))
        .withColumn("hour", F.floor(uniform("order_idx", 10) * 24).cast("int")))
    candidates = candidates.withColumn("order_date", F.date_add(F.lit("2026-09-01").cast("date"), F.col("day_idx")))
    probability = (F.when(F.col("hour").between(9, 20), .72).otherwise(.25)
        * F.when(F.dayofweek("order_date").isin(1, 7), .75).otherwise(1.)
        * (0.95 + F.col("day_idx") / 600.))
    orders = (candidates.filter(uniform("order_idx", 11) < probability)
        .withColumn("customer_idx", F.when(uniform("order_idx", 12) < .20,
            F.floor(uniform("order_idx", 13) * 500)).otherwise(500 + F.floor(uniform("order_idx", 13) * 9300)).cast("long"))
        .join(customers.select("customer_idx", "customer_id", "tier", "region"), "customer_idx")
        .withColumn("order_id", identifier("O", F.col("order_idx")))
        .withColumn("order_ts", (F.unix_timestamp("order_date") + F.col("hour") * 3600
            + F.floor(uniform("order_idx", 14) * 3600)).cast("timestamp"))
        .withColumn("channel", F.when(uniform("order_idx", 15) < .58, "web")
            .when(uniform("order_idx", 15) < .90, "mobile").otherwise("partner"))
        .withColumn("gateway", F.when(uniform("order_idx", 16) < .7, "GatewayA")
            .when(uniform("order_idx", 16) < .9, "GatewayB").otherwise("GatewayC"))
        .withColumn("ingestion_date", F.col("order_date"))
        .withColumn("line_count", F.when(uniform("order_idx", 17) < .5, 2).otherwise(1)))
    lines = (orders.withColumn("line_number", F.explode(F.sequence(F.lit(1), F.col("line_count"))))
        .withColumn("line_key", F.concat_ws("-", "order_id", "line_number"))
        .withColumn("product_idx", F.when(F.col("tier") == "enterprise",
            150 + F.floor(uniform("line_key", 18) * 50)).otherwise(
                F.floor(F.pow(uniform("line_key", 18), 2) * 150)).cast("long"))
        .join(catalog.select("product_idx", "product_id", "unit_price"), "product_idx")
        .withColumn("quantity", F.when(uniform("line_key", 19) < .80, 1).otherwise(2))
        .withColumn("line_amount", F.round(F.col("unit_price") * F.col("quantity"), 2)))
    totals = lines.groupBy("order_id").agg(F.round(F.sum("line_amount"), 2).alias("order_amount"))
    return lines, orders.join(totals, "order_id")


def build_payments(orders):
    incident = ((F.col("order_date") == F.lit("2026-10-10").cast("date"))
        & F.col("hour").between(10, 13) & (F.col("gateway") == "GatewayA"))
    first = (orders.withColumn("incident", incident)
        .withColumn("failed", uniform("order_idx", 30) < F.when(incident, .60).otherwise(.02))
        .withColumn("retry", F.col("failed") & (uniform("order_idx", 31) < .75)))
    second_failed = uniform("order_idx", 32) < F.when(F.col("incident"), .60).otherwise(.02)
    outcomes = first.withColumn("captured", ~F.col("failed") | (F.col("retry") & ~second_failed))

    def attempt(df, number, failed):
        return (df.withColumn("attempt_number", F.lit(number))
            .withColumn("event_type", F.lit("attempt"))
            .withColumn("status", F.when(failed, "failed").otherwise("succeeded"))
            .withColumn("event_ts", (F.col("order_ts").cast("long") + (number - 1) * 90).cast("timestamp"))
            .withColumn("latency_ms", F.round(F.when(F.col("incident"), 5000 + uniform("order_idx", 33) * 15000)
                .otherwise(100 + uniform("order_idx", 33) * 700)).cast("long"))
            .withColumn("amount", F.col("order_amount"))
            .withColumn("payment_event_id", F.concat_ws("-", "order_id", F.lit(f"attempt{number}"))))

    columns = ["payment_event_id", "order_id", "gateway", "attempt_number", "event_type", "status",
               "event_ts", "amount", "latency_ms", "ingestion_date"]
    payments = attempt(first, 1, F.col("failed")).select(*columns).unionByName(
        attempt(first.filter("retry"), 2, second_failed).select(*columns))
    refunds = (outcomes.filter(F.col("captured") & (uniform("order_idx", 34) < .025))
        .withColumn("payment_event_id", F.concat_ws("-", "order_id", F.lit("refund")))
        .withColumn("attempt_number", F.when(F.col("failed"), 2).otherwise(1))
        .withColumn("event_type", F.lit("refund")).withColumn("status", F.lit("refunded"))
        .withColumn("event_ts", (F.col("order_ts").cast("long") + 600).cast("timestamp"))
        .withColumn("amount", F.col("order_amount")).withColumn("latency_ms", F.lit(0)))
    return payments.unionByName(refunds.select(*columns)), outcomes


def customer_events(customers, outcomes):
    fields = ["event_id", "customer_id", "name", "region", "tier", "operation", "effective_ts", "sequence", "ingestion_date"]
    initial = (customers.withColumn("event_id", F.concat_ws("-", "customer_id", F.lit("initial")))
        .withColumn("operation", F.lit("I"))
        .withColumn("effective_ts", F.lit("2026-09-01 00:00:00").cast("timestamp"))
        .withColumn("sequence", F.lit(1)).withColumn("ingestion_date", F.lit("2026-09-01").cast("date")))
    affected = outcomes.filter(F.col("incident") & ~F.col("captured") & (F.col("tier") == "enterprise")).select("customer_id").distinct()
    downgrade = (customers.join(affected, "customer_id")
        .filter(uniform("customer_idx", 40) < .25)
        .withColumn("tier", F.lit("pro"))
        .withColumn("effective_ts", (F.lit("2026-10-11 00:00:00").cast("timestamp").cast("long")
            + F.floor(uniform("customer_idx", 41) * 14) * 86400).cast("timestamp")))
    updates = (customers.filter((F.col("customer_idx") >= 500) & (F.col("customer_idx") < 800))
        .withColumn("tier", F.lit("pro"))
        .withColumn("effective_ts", F.lit("2026-09-20 00:00:00").cast("timestamp")))
    changes = (downgrade.unionByName(updates)
        .withColumn("event_id", F.concat_ws("-", "customer_id", F.lit("update")))
        .withColumn("operation", F.lit("U")).withColumn("sequence", F.lit(2))
        .withColumn("ingestion_date", F.to_date("effective_ts")))
    # Reserved IDs have no orders: safely demonstrate deletes.
    deletes = (customers.filter(F.col("customer_idx") >= 9900)
        .withColumn("event_id", F.concat_ws("-", "customer_id", F.lit("delete")))
        .withColumn("operation", F.lit("D")).withColumn("sequence", F.lit(2))
        .withColumn("effective_ts", F.lit("2026-10-01 00:00:00").cast("timestamp"))
        .withColumn("ingestion_date", F.to_date("effective_ts")))
    return initial.select(*fields).unionByName(changes.select(*fields)).unionByName(deletes.select(*fields))


def dirty_lines(lines):
    cohort = uniform("line_key", 50)
    fields = ["order_id", "line_key", "line_number", "customer_id", "product_id", "order_ts", "channel",
              "quantity", "unit_price", "line_amount", "ingestion_date"]
    dirty = (lines.withColumn("customer_id", F.when(cohort < .003, F.lit(None)).otherwise(F.col("customer_id")))
        .withColumn("line_amount", F.when((cohort >= .003) & (cohort < .005), -1.).otherwise(F.col("line_amount")))
        .withColumn("order_ts", F.when((cohort >= .005) & (cohort < .006),
            F.lit("2099-01-01 00:00:00").cast("timestamp")).otherwise(F.col("order_ts"))))
    return dirty.select(*fields).unionByName(dirty.filter((cohort >= .006) & (cohort < .011)).select(*fields))


def validate(spark, w, batch, paths):
    dfs = {name: spark.read.parquet(path) for name, path in paths.items()}
    report = {"batch": batch, "paths": paths, "counts": {name: df.count() for name, df in dfs.items()}}
    report["file_counts"] = {name: len(list(files_below(w, path))) for name, path in paths.items()}
    report["ingestion_dates"] = {name: df.agg(F.min("ingestion_date").cast("string").alias("first"),
        F.max("ingestion_date").cast("string").alias("last")).first().asDict() for name, df in dfs.items()}
    lines = dfs["orders"].dropDuplicates(["line_key"])
    report["quality"] = lines.agg(
        F.sum(F.col("customer_id").isNull().cast("long")).alias("missing_customer_lines"),
        F.sum((F.col("line_amount") <= 0).cast("long")).alias("nonpositive_lines"),
        F.sum((F.col("order_ts") > F.current_timestamp()).cast("long")).alias("future_lines")
    ).first().asDict()
    report["quality"]["duplicate_lines"] = report["counts"]["orders"] - lines.count()
    payments = dfs["payments"]
    report["distinct_orders"] = lines.select("order_id").distinct().count()
    report["quality"]["unknown_payment_statuses"] = payments.filter(~F.col("status").isin("succeeded", "failed", "refunded")).count()
    assert all(value > 0 for value in report["quality"].values()), report["quality"]
    valid = lines.filter(F.col("customer_id").isNotNull() & (F.col("line_amount") > 0) & (F.col("order_ts") < F.current_timestamp()))
    # Initial cohort plus downgrade timestamps preserve tier at order time.
    customer = dfs["customers"].filter(F.col("operation") == "I").select("customer_id", "tier")
    downgrades = dfs["customers"].filter((F.col("operation") == "U") & (F.col("tier") == "pro") & (F.col("effective_ts") >= F.lit("2026-10-11").cast("timestamp"))).select("customer_id", "effective_ts")
    report["initial_enterprise_customer_share"] = customer.filter(F.col("tier") == "enterprise").count() / max(customer.count(), 1)
    basket = valid.groupBy("order_id", "customer_id").agg(F.sum("line_amount").alias("order_value"), F.min("order_ts").alias("order_ts"))
    before = basket.filter(F.col("order_ts") < F.lit("2026-10-10").cast("timestamp")).join(customer, "customer_id")
    pre = before.agg(F.sum("order_value").alias("all"), F.sum(F.when(F.col("tier") == "enterprise", F.col("order_value")).otherwise(0.)).alias("enterprise")).first()
    report["pre_outage_enterprise_value_share"] = pre.enterprise / pre.all
    attempts = payments.filter(F.col("event_type") == "attempt").withColumn("period",
        F.when((F.to_date("event_ts") == F.lit("2026-10-10").cast("date")) & F.hour("event_ts").between(10, 13), "outage")
        .when(F.col("event_ts") >= F.lit("2026-10-10 14:00:00").cast("timestamp"), "recovery").otherwise("baseline"))
    stats = attempts.filter(F.col("status").isin("succeeded", "failed")).groupBy("gateway", "period").agg(
        F.count("*").alias("attempts"), F.avg((F.col("status") == "failed").cast("double")).alias("failure_rate"),
        F.avg("latency_ms").alias("mean_latency_ms"), F.sum((F.col("attempt_number") > 1).cast("long")).alias("retries"))
    report["gateway_health"] = [row.asDict() for row in stats.orderBy("gateway", "period").toLocalIterator()]
    gateway_counts = payments.filter((F.col("event_type") == "attempt") & (F.col("attempt_number") == 1)).groupBy("gateway").count()
    report["gateway_order_counts"] = {row.gateway: row["count"] for row in gateway_counts.toLocalIterator()}
    status = payments.groupBy("order_id").agg(
        F.max((F.col("status") == "succeeded").cast("int")).alias("captured"),
        F.max((F.col("status") == "refunded").cast("int")).alias("refunded"),
        F.first("gateway").alias("gateway"),
        F.max("attempt_number").alias("max_attempt"))
    clean_payment_orders = payments.filter(~F.col("status").isin("succeeded", "failed", "refunded")).select("order_id").distinct()
    financial = basket.join(status, "order_id").join(clean_payment_orders, "order_id", "left_anti")
    report["financial_excluded_unknown_status_orders"] = clean_payment_orders.count()
    amounts = financial.agg(
        F.sum(F.when(F.col("captured") == 1, F.col("order_value")).otherwise(0.)).alias("captured_value"),
        F.sum(F.when(F.col("refunded") == 1, F.col("order_value")).otherwise(0.)).alias("refunded_value"),
        F.sum(F.when(F.col("captured") == 0, F.col("order_value")).otherwise(0.)).alias("terminal_failed_value")
    ).first().asDict()
    amounts["net_revenue"] = amounts["captured_value"] - amounts["refunded_value"]
    report["valid_record_financials_usd"] = amounts
    incident_orders = financial.filter((F.col("gateway") == "GatewayA")
        & (F.to_date("order_ts") == F.lit("2026-10-10").cast("date")) & F.hour("order_ts").between(10, 13))
    report["incident_terminal_failed_value_usd"] = incident_orders.filter(F.col("captured") == 0).agg(F.sum("order_value")).first()[0]
    report["orders_recovered_by_retry"] = financial.filter((F.col("captured") == 1) & (F.col("max_attempt") > 1)).count()
    affected = (incident_orders.filter(F.col("captured") == 0)
        .join(customer.filter(F.col("tier") == "enterprise"), "customer_id").select("customer_id").distinct())
    report["affected_enterprise_customers"] = affected.count()
    report["affected_enterprise_downgrades"] = affected.join(downgrades, "customer_id").select("customer_id").distinct().count()
    report["integrity"] = {
        "unknown_product_lines": lines.join(dfs["products"].select("product_id"), "product_id", "left_anti").count(),
        "unexpected_customer_lines": lines.filter(F.col("customer_id").isNotNull()).join(customer.select("customer_id"), "customer_id", "left_anti").count(),
        "orphan_payment_events": payments.join(lines.select("order_id").distinct(), "order_id", "left_anti").count(),
    }
    assert all(value == 0 for value in report["integrity"].values()), report["integrity"]
    assert report["ingestion_dates"]["orders"] == {"first": "2026-09-01", "last": "2026-10-31"}
    assert report["distinct_orders"] > 100000
    primary = {r["period"]: r for r in report["gateway_health"] if r["gateway"] == "GatewayA"}
    assert .01 < primary["baseline"]["failure_rate"] < .035, primary
    assert .50 < primary["outage"]["failure_rate"] < .70, primary
    assert primary["recovery"]["failure_rate"] < .035, primary
    assert .42 < report["pre_outage_enterprise_value_share"] < .58, report
    assert report["affected_enterprise_downgrades"] > 0, report
    Path("reports").mkdir(exist_ok=True)
    Path(f"reports/{batch}.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_json(w, f"{ROOT}/_control/reports/{batch}.json", report)
    print(json.dumps(report, indent=2), flush=True)
    return report


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", default="Faisal")
    parser.add_argument("--day", help="Generate one new day after historical generation")
    parser.add_argument("--validate-only", action="store_true", help="Recompute verification from published files without generating data")
    args = parser.parse_args()
    if args.day and args.day != "2026-11-01":
        raise ValueError("Only the reserved incremental day 2026-11-01 is supported by v1")
    w = WorkspaceClient(profile=args.profile)
    batch = f"day-{args.day}-{VERSION}" if args.day else f"historical-{VERSION}"
    control = f"{ROOT}/_control/batches/{batch}.json"
    state = read_json(w, control)
    if state and state.get("status") == "complete" and not args.validate_only:
        print(f"SKIP {batch}: complete, no files or events added", flush=True)
        return
    spark = DatabricksSession.builder.profile(args.profile).serverless(True).getOrCreate()
    spark.conf.set("spark.sql.session.timeZone", "UTC")
    if args.validate_only:
        if not state or state.get("status") not in ("published", "complete") or args.day:
            raise RuntimeError("Validation-only requires published historical data")
        validate(spark, w, batch, {name: info["published"] for name, info in state["sources"].items()})
        return
    if not state:
        state = {"batch": batch, "status": "preparing", "sources": {}}
        write_json(w, control, state, overwrite=False)
    customers = base_customers(spark)
    catalog = products(spark)
    lines, orders = build_orders(spark, customers, catalog, args.day)
    payments, outcomes = build_payments(orders)
    if args.day:
        historical = read_json(w, f"{ROOT}/_control/batches/historical-{VERSION}.json")
        if not historical or historical.get("status") != "complete":
            raise RuntimeError("Historical generation must complete before incremental mode")
        # Derive the historical tier changes and apply the latest state for later orders.
        historical_events = spark.read.parquet(historical["sources"]["customers"]["published"])
        changes = historical_events.filter(F.col("operation") == "U").select("customer_id", F.col("tier").alias("updated_tier"))
        customers = customers.join(changes, "customer_id", "left").withColumn("tier", F.coalesce("updated_tier", "tier")).drop("updated_tier")
        lines, orders = build_orders(spark, customers, catalog, args.day)
        payments, outcomes = build_payments(orders)
        customer_source = (customers.filter(F.col("customer_idx").between(800, 809))
            .withColumn("event_id", F.concat_ws("-", "customer_id", F.lit(args.day)))
            .withColumn("operation", F.lit("U")).withColumn("sequence", F.lit(3))
            .withColumn("effective_ts", F.lit(args.day).cast("timestamp"))
            .withColumn("ingestion_date", F.lit(args.day).cast("date"))
            .select("event_id", "customer_id", "name", "region", "tier", "operation", "effective_ts", "sequence", "ingestion_date"))
        catalog = catalog.filter(F.lit(False))  # immutable catalog; no duplicate products
    else:
        customer_source = customer_events(customers, outcomes)
    payments = payments.withColumn("status", F.when(uniform("payment_event_id", 51) < .001, "UNKNOWN").otherwise(F.col("status")))
    sources = {"products": catalog, "customers": customer_source, "orders": dirty_lines(lines), "payments": payments}
    if args.day:
        # Products are unchanged: leave their existing files in place, without
        # attempting to publish an empty incremental product batch.
        sources.pop("products")
    for name, frame in sources.items():
        info = state["sources"].get(name)
        if info and info.get("staged"):
            print(f"Reuse completed staging: {name}", flush=True)
            continue
        path = f"{ROOT}/_staging/{batch}/{uuid.uuid4().hex}/{name}"
        print(f"Generating {name} on serverless...", flush=True)
        frame.repartition(2, "ingestion_date").write.mode("error").partitionBy("ingestion_date").parquet(path)
        state["sources"][name] = {"staged": path, "published": f"{ROOT}/sources/{name}/batch={batch}"}
        write_json(w, control, state)
    for name, info in state["sources"].items():
        info["file_count"] = publish(w, name, info["staged"], info["published"])
        write_json(w, control, state)
    state["status"] = "published"
    write_json(w, control, state)
    if not args.day:
        validate(spark, w, batch, {name: info["published"] for name, info in state["sources"].items()})
    else:
        print("Incremental day published; pipeline checks belong to Step 4", flush=True)
    state["status"] = "complete"
    write_json(w, control, state)
    print(f"COMPLETE {batch}", flush=True)


if __name__ == "__main__":
    main()
